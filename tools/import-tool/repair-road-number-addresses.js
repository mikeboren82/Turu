// TuRu - THE CLEANER: DB-wide repair of ROAD NUMBER stored as a street (failure class of the
// "חוות ארץ האיילים" regression: address "367, ביתר עילית" for a farm in כפר עציון; same class:
// "3199, ערד", "4650, בית אריה - עופרים", and 284 playground titles generated from it).
// Cause: reverse geocoding returns a highway reference in `road` for a point beside a highway; the frozen
// enrich script wrote "<road>, <geocoder city>" and the naming function built titles from it. Roots fixed
// in cleaner/reverse.js + playgroundNaming (both twins). This closes what is already stored:
//   ADDRESS  "<digits>, <anything>"  -> NULL  (no street is known; the geocoder's city guess beside it is
//            not evidence either - it contradicted the real city on the regression row). Only addresses the
//            system itself derived are touched (address_source NULL / cleaner:reverse_geocode / twin_merge),
//            guarded by the exact value seen.
//   TITLE    a GENERATED playground title that carries the road number -> regenerated by the shared naming
//            function from the canonical city (never an admin-confirmed or official name).
// Dry run by default:   node repair-road-number-addresses.js [--apply]
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const { getClient } = require('./supabase');
const { all } = require('./cleaner/discover');
const { generatePlaygroundDisplayName } = require('./playgroundNaming');

const APPLY = process.argv.includes('--apply');
const ROAD_ADDR = /^\s*\d{2,4}\s*(,|$)/;
const DERIVED = new Set([null, undefined, '', 'cleaner:reverse_geocode', 'cleaner:twin_merge']);

(async () => {
  const { client } = await getClient();
  const acts = await all(client, 'activities', 'id, name, name_source, category, locations!inner(id, address, city, address_source)', (q) => q.eq('status', 'approved').not('locations.address', 'is', null));
  const rows = acts.filter((a) => ROAD_ADDR.test(a.locations.address || ''));
  const plan = []; const counts = { rows: rows.length, addressCleared: 0, addressSkippedNotDerived: 0, titleRegenerated: 0, titleKept: 0 };
  const seenLoc = new Set();
  for (const a of rows) {
    const L = a.locations; const roadNo = (L.address.match(/^\s*(\d{2,4})/) || [])[1];
    const p = { id: a.id, name: a.name, category: a.category, city: L.city, address: L.address, address_source: L.address_source || null, clearAddress: false, newName: null };
    if (DERIVED.has(L.address_source)) { p.clearAddress = true; if (!seenLoc.has(L.id)) { seenLoc.add(L.id); counts.addressCleared++; } } else counts.addressSkippedNotDerived++;
    const generated = a.category === 'גן שעשועים' && a.name_source !== 'admin_confirmed' && a.name_source !== 'official' && new RegExp(`[–-]\\s*${roadNo}\\s*(,|$)`).test(a.name || '');
    if (generated) { const g = generatePlaygroundDisplayName({ officialName: null, address: null, city: L.city }); if (g.name && g.name !== a.name) { p.newName = g.name; p.nameSource = g.nameSource; counts.titleRegenerated++; } else counts.titleKept++; } else counts.titleKept++;
    p.locationId = L.id; plan.push(p);
  }
  if (APPLY) {
    const cleared = new Set();
    for (const p of plan) {
      if (p.clearAddress && !cleared.has(p.locationId)) { cleared.add(p.locationId); let q = client.from('locations').update({ address: null }).eq('id', p.locationId).eq('address', p.address); q = p.address_source ? q.eq('address_source', p.address_source) : q.is('address_source', null); const { error } = await q; if (error) console.log('  address write failed', p.id, error.message); }
      if (p.newName) { const { error } = await client.from('activities').update({ name: p.newName, name_source: p.nameSource }).eq('id', p.id).eq('name', p.name); if (error) console.log('  name write failed', p.id, error.message); }
    }
  }
  const file = path.join(__dirname, `road-number-address-repair-${new Date().toISOString().slice(0, 10)}${APPLY ? '-applied' : '-dryrun'}.json`);
  fs.writeFileSync(file, JSON.stringify({ generatedAt: new Date().toISOString(), applied: APPLY, counts, plan }, null, 2));
  console.log(`${APPLY ? 'APPLIED' : 'DRY RUN'}`, JSON.stringify(counts), '->', path.basename(file));
  plan.filter((p) => p.category !== 'גן שעשועים').forEach((p) => console.log(`  non-playground: ${p.name} | "${p.address}" (city ${p.city}) -> address ${p.clearAddress ? 'NULL' : 'kept (' + p.address_source + ')'}`));
  plan.filter((p) => p.newName).slice(0, 8).forEach((p) => console.log(`  title: "${p.name}" -> "${p.newName}"`));
})().catch((e) => { console.error(e); process.exit(1); });
