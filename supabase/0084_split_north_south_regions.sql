-- TuRu - עידון טקסונומיית האזורים: פיצול "הצפון והעמק" ל-"הצפון והגליל" / "עמק יזרעאל והעמקים",
-- ופיצול "השפלה והדרום" ל-"השפלה" / "הדרום והנגב". הרשימה המלאה (9 אזורים, סדר עדכני):
-- גוש דן והמרכז, השרון, ירושלים והסביבה, חיפה והקריות, הצפון והגליל, עמק יזרעאל והעמקים,
-- השפלה, הדרום והנגב, יו"ש והבנימין. שוריינת מ-constants/categoryValues.json (ומהעותק הזהה
-- ב-supabase/functions/_shared/categoryValues.json) - יש לעדכן את שניהם יחד עם המיגרציה הזו.
--
-- שיוך-מחדש של שורות קיימות (השלב היחיד שאין לו נוסחה גיאוגרפית מדויקת): מיפוי עיר→אזור-חדש
-- ידני, שנבנה מבדיקת התפלגות הערים בפועל תחת כל אחד משני האזורים הישנים (בטרמינל, session
-- 2026-09-13) - לא שירות מיפוי כללי, ולא ניסיון לתקן דליפות-גבול קיימות (למשל ישובים ביו"ש
-- שכבר תויגו בטעות תחת "השפלה והדרום" - נשארים כפי שהיו, רק תחת שם-האזור-החדש התואם ביותר,
-- 'השפלה' כברירת מחדל). ערכי עיר בערבית/עם סימני-כיווניות בלתי-נראים לא נכללו ברשימות המפורשות
-- למטה (סיכון match לא-מדויק ב-UPDATE המוני) - נופלים לברירת המחדל של כל אזור; מיעוט קטן מהן
-- (כ-2% מהשורות המושפעות) עשוי לנחות באזור-המשנה הפחות מדויק גיאוגרפית כתוצאה מכך.

-- טרנזקציה אחת - אם משהו נכשל באמצע, לא נשארים עם הטבלה בלי constraint בכלל (drop הצליח
-- אבל ה-add בסוף לא רץ).
begin;

-- 1) מסירים קודם את ה-constraint הישן - הוא לא מכיר עדיין את ערכי-האזור החדשים, אז ה-UPDATE-ים
--    למטה (שמכניסים בדיוק את הערכים האלה) היו נכשלים תחתיו. ה-constraint החדש (סעיף 4) חוזר
--    ומאמת את כל הטבלה אחרי שהעדכון כבר הושלם.
alter table public.locations drop constraint if exists locations_region_check;

-- 2) "הצפון והעמק" -> "הצפון והגליל" (ברירת מחדל) / "עמק יזרעאל והעמקים" (רשימת ערים מפורשת)
update public.locations
set region = case
  when city = any (array[
    'יקנעם עילית','מועצה אזורית עמק יזרעאל','עפולה','מגדל העמק','מועצה אזורית עמק הירדן',
    'מועצה אזורית מגידו','כפר תבור','רמת ישי','מועצה אזורית עמק המעיינות','טבריה','יבנאל',
    'מגדל','כנרת','פוריה כפר עבודה','עין גב','בית זרע','קיבוץ בית זרע','תבור','היוגב','נצרת'
  ]::text[])
    then 'עמק יזרעאל והעמקים'
  else 'הצפון והגליל'
end
where region = 'הצפון והעמק';

-- 3) "השפלה והדרום" -> "השפלה" (ברירת מחדל) / "הדרום והנגב" (רשימת ערים מפורשת)
update public.locations
set region = case
  when city = any (array[
    'באר שבע','אילת','אשקלון','שדרות','ערד','מועצה אזורית שדות נגב','מועצה אזורית חוף אשקלון',
    'מועצה אזורית מרחבים','מועצה אזורית אשכול','מועצה אזורית רמת נגב','דימונה','עומר','מיתר',
    'מועצה אזורית בני שמעון','נתיבות','אופקים','ירוחם','מועצה אזורית חבל אילות','מצפה רמון',
    'מועצה אזורית שער הנגב','להבים','מועצה אזורית תמר','הנגב','רהט','מועצה אזורית הערבה התיכונה',
    'כרם שלום','כפר עזה','עזריה','בית חגי'
  ]::text[])
    then 'הדרום והנגב'
  else 'השפלה'
end
where region = 'השפלה והדרום';

-- 4) עדכון ה-CHECK constraint לרשימת 9 האזורים החדשה (מחליף את 0007_update_regions.sql)
alter table public.locations add constraint locations_region_check
  check (region in (
    'גוש דן והמרכז',
    'השרון',
    'ירושלים והסביבה',
    'חיפה והקריות',
    'הצפון והגליל',
    'עמק יזרעאל והעמקים',
    'השפלה',
    'הדרום והנגב',
    'יו"ש והבנימין'
  ));

commit;
